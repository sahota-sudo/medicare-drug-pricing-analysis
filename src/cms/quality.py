"""
Data quality assessment.

This runs before any analysis and writes docs/data_quality.md. The
point is not to produce a clean dataset -- the CMS file is already
clean in the ordinary sense. The point is to quantify the things that
will distort an analysis if they are not handled, and to state how
each one is handled.
"""

from __future__ import annotations

import pandas as pd


def profile(long: pd.DataFrame) -> dict[str, pd.DataFrame | pd.Series]:
    """Quantify every issue the transforms are designed to handle."""
    program = long["program"].iloc[0]
    years = sorted(long["data_year"].unique())
    checks: dict[str, pd.DataFrame | pd.Series] = {}

    # 1. Coverage: how many drugs were not on the market in each year.
    checks["coverage_by_year"] = (
        long.groupby("data_year")
        .agg(
            rows=("marketed", "size"),
            marketed=("marketed", "sum"),
            not_marketed=("marketed", lambda s: (~s).sum()),
        )
        .assign(pct_not_marketed=lambda d: d["not_marketed"] / d["rows"])
    )

    # 2. Entry and exit: drugs appearing or disappearing mid-window.
    #    These are the rows that break a naive CAGR.
    keys = ["hcpcs_code"] if "hcpcs_code" in long.columns else \
        ["brand_name", "generic_name", "manufacturer"]
    marketed = long[long["marketed"]]
    span = marketed.groupby(keys, dropna=False)["data_year"].agg(["min", "max", "count"])
    checks["entry_exit"] = pd.Series(
        {
            "present_all_years": int((span["count"] == len(years)).sum()),
            "entered_after_first_year": int((span["min"] > years[0]).sum()),
            "absent_in_final_year": int((span["max"] < years[-1]).sum()),
            "intermittent": int(
                ((span["max"] - span["min"] + 1) != span["count"]).sum()
            ),
        }
    )

    # 3. Outlier flags: CMS's own warning that per-unit spending for a
    #    drug-year is distorted by outlier records.
    checks["outlier_flags_by_year"] = (
        long.groupby("data_year")["outlier_flag"]
        .agg(flagged="sum", known="count")
        .assign(pct_flagged=lambda d: d["flagged"] / d["known"])
    )

    # 4. Name ambiguity: '*' = several names share one code,
    #    '**' = CMS had no name at all.
    checks["name_quality"] = pd.Series(
        {
            "rows": len(long),
            "multiple_names": int(long["has_multiple_names"].sum()),
            "name_unavailable": int(long["name_unavailable"].sum()),
        }
    )

    # 5. Internal consistency: does spending / units reproduce the
    #    published average price? A mismatch means the grain is wrong.
    recomputed = long["total_spending_usd"] / long["total_dosage_units"]
    delta = (recomputed - long["avg_spend_per_dosage_unit"]).abs()
    relative = delta / long["avg_spend_per_dosage_unit"].abs()
    checks["price_reconciliation"] = pd.Series(
        {
            "comparable_rows": int(relative.notna().sum()),
            "within_0.1pct": int((relative < 0.001).sum()),
            "within_1pct": int((relative < 0.01).sum()),
            "max_relative_gap": float(relative.max(skipna=True)),
        }
    )

    # 6. Part D only: the double-count trap.
    if "manufacturer" in long.columns and long["manufacturer"].notna().any():
        overall = long["manufacturer"].eq("Overall")
        latest = long[long["data_year"] == years[-1]]
        checks["part_d_double_count"] = pd.Series(
            {
                "overall_rows": int(overall.sum()),
                "manufacturer_rows": int((~overall).sum()),
                "naive_total_usd_bn": float(
                    latest["total_spending_usd"].sum() / 1e9
                ),
                "correct_total_usd_bn": float(
                    latest.loc[latest["manufacturer"].eq("Overall"),
                               "total_spending_usd"].sum() / 1e9
                ),
            }
        )
        checks["part_d_double_count"]["overstatement_pct"] = (
            checks["part_d_double_count"]["naive_total_usd_bn"]
            / checks["part_d_double_count"]["correct_total_usd_bn"] - 1
        )

    checks["_program"] = program
    return checks


def _fmt(value: float, kind: str = "num") -> str:
    if pd.isna(value):
        return "n/a"
    if kind == "pct":
        return f"{value:.1%}"
    if kind == "usd_bn":
        return f"${value:,.1f}B"
    return f"{value:,.0f}"


def to_markdown(profiles: dict[str, dict]) -> str:
    """Render one profile per program into a single report."""
    lines = [
        "# Data quality assessment",
        "",
        "Generated by `python -m cms.quality`. Every figure is measured from",
        "the raw CMS files, not asserted.",
        "",
    ]

    for program, checks in profiles.items():
        lines += [f"## {program}", ""]

        coverage = checks["coverage_by_year"]
        lines += [
            "### Blank years are not zeros",
            "",
            "A blank measure means the drug had no Medicare spending that year,",
            "normally because it had not launched. Filling blanks with zero turns",
            "a later launch into an apparent collapse; dropping the rows discards",
            "the launch date. Both are preserved here via a `marketed` flag.",
            "",
            "| Year | Rows | Marketed | Not marketed | % not marketed |",
            "|---|---|---|---|---|",
        ]
        for year, row in coverage.iterrows():
            lines.append(
                f"| {year} | {_fmt(row['rows'])} | {_fmt(row['marketed'])} | "
                f"{_fmt(row['not_marketed'])} | {_fmt(row['pct_not_marketed'], 'pct')} |"
            )

        entry = checks["entry_exit"]
        lines += [
            "",
            "### Entry and exit",
            "",
            f"- Present in every year: **{_fmt(entry['present_all_years'])}**",
            f"- Entered after the first year: **{_fmt(entry['entered_after_first_year'])}**",
            f"- Absent in the final year: **{_fmt(entry['absent_in_final_year'])}**",
            f"- Intermittent (gap in the middle): **{_fmt(entry['intermittent'])}**",
            "",
            "A five-year CAGR is only meaningful for the first group. Any product",
            "that entered mid-window has a CAGR computed over its own marketed",
            "span, and the span length is reported alongside it.",
            "",
        ]

        outliers = checks["outlier_flags_by_year"]
        latest_year = outliers.index.max()
        lines += [
            "### CMS outlier flags",
            "",
            "CMS sets this flag when a drug's average spending per dosage unit is",
            "substantially affected by outlier records. Flagged rows are retained",
            "but excluded from price-trend conclusions.",
            "",
            f"- Flagged in {latest_year}: **{_fmt(outliers.loc[latest_year, 'flagged'])}** "
            f"of {_fmt(outliers.loc[latest_year, 'known'])} "
            f"({_fmt(outliers.loc[latest_year, 'pct_flagged'], 'pct')})",
            "",
        ]

        names = checks["name_quality"]
        lines += [
            "### Name ambiguity",
            "",
            f"- Rows where several brand or generic names share one code (`*`): "
            f"**{_fmt(names['multiple_names'])}**",
            f"- Rows where CMS had no name and used the code description (`**`): "
            f"**{_fmt(names['name_unavailable'])}**",
            "",
            "Markers are stripped into boolean columns rather than left on the",
            "name, so joins and groupings do not silently split one drug in two.",
            "",
        ]

        recon = checks["price_reconciliation"]
        lines += [
            "### Internal consistency",
            "",
            f"Recomputing spending ÷ dosage units reproduces CMS's published average",
            f"price within 0.1% on **{_fmt(recon['within_0.1pct'])}** of "
            f"**{_fmt(recon['comparable_rows'])}** comparable rows "
            f"(largest relative gap {_fmt(recon['max_relative_gap'], 'pct')}).",
            "",
        ]

        if "part_d_double_count" in checks:
            dc = checks["part_d_double_count"]
            lines += [
                "### The Part D double-count",
                "",
                "Part D ships an `Overall` row per drug *and* one row per",
                "manufacturer. Summing the file as delivered counts multi-source",
                "drugs twice, and by a different factor for each, since the",
                "manufacturer count ranges from 1 to 46.",
                "",
                f"- Naive total for the latest year: "
                f"**{_fmt(dc['naive_total_usd_bn'], 'usd_bn')}**",
                f"- Correct total (`Overall` rows only): "
                f"**{_fmt(dc['correct_total_usd_bn'], 'usd_bn')}**",
                f"- Overstatement: **{_fmt(dc['overstatement_pct'], 'pct')}**",
                "",
            ]

    return "\n".join(lines)
